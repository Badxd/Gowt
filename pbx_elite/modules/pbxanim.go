// pbxDirect lists commands that PBX Elite exposes directly (.love, .crush ...).
// Names that clash with an already-registered command are skipped in init().
var pbxDirect = []string{"love", "crush", "rain", "ahh", "brain", "call", "theart", "wtf", "ding", "hypo", "gangstar", "charging", "dino", "nolove", "ror", "plane", "deploy", "musicplayer", "snake", "loveu", "hmm", "tank", "cat", "gm", "gn", "shoot", "cobra", "helicopter", "gf", "run", "thumb", "patart", "surprised", "shock"}

func init() {
	// merge PBX frames into the main list (never override an existing Go animation)
	for k, v := range pbxFrames {
		if _, ok := animationList[k]; !ok {
			animationList[k] = v
		}
	}
	animationList["shock"] = animationList["surprised"]

	taken := map[string]bool{}
	for _, m := range allModules {
		for _, c := range m.Commands {
			taken[c.Pattern] = true
		}
	}
	// commands that live in files initialised after this one
	for _, n := range []string{"addsudo", "removesudo", "sudolist", "approve", "block", "unblock", "warn", "resetwarn", "sticker", "s", "ttt", "vv", "weather", "tr", "translate", "tinyurl", "yt", "ytmp3", "song", "img", "calc", "remind", "bass", "save", "start", "help", "ping"} {
		taken[n] = true
	}

	var cmds []CommandInfo
	for _, name := range pbxDirect {
		if taken[name] {
			continue
		}
		n := name
		cmds = append(cmds, CommandInfo{
			Pattern: n,
			Sudo:    true,
			Handler: func(v *events.Message, args []string) error {
				frames := animationList[n]
				if len(frames) == 1 {
					return ReplyErr(v, frames[0])
				}
				return playFrames(v, frames)
			},
		})
	}
	Register(ModuleInfo{
		Name:        "PBXAnimations",
		Description: "PBX Elite animation + ASCII art commands",
		Commands:    cmds,
	})
}
