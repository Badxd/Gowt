// carbon — generate a code screenshot via carbon.now.sh API (unofficial)
// Usage: .carbon [lang] <code> OR reply to a code message with .carbon

const carbonAPI = "https://carbonara.solopov.dev/api/cook"

type carbonRequest struct {
	Code            string `json:"code"`
	Language        string `json:"language"`
	Theme           string `json:"theme"`
	BackgroundColor string `json:"backgroundColor"`
	WindowTheme     string `json:"windowTheme"`
	FontSize        string `json:"fontSize"`
	FontFamily      string `json:"fontFamily"`
	LineNumbers     bool   `json:"lineNumbers"`
	ExportSize      string `json:"exportSize"`
}

func fetchCarbonImage(code, lang string) ([]byte, error) {
	payload := carbonRequest{
		Code:            code,
		Language:        lang,
		Theme:           "dracula",
		BackgroundColor: "rgba(27,27,27,1)",
		WindowTheme:     "none",
		FontSize:        "14px",
		FontFamily:      "Fira Code",
		LineNumbers:     true,
		ExportSize:      "2x",
	}

	body, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, carbonAPI, bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "PBX-Elite/1.0")

	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("carbon API returned %d", resp.StatusCode)
	}

	return io.ReadAll(resp.Body)
}

func carbonHandler(v *events.Message, args []string) error {
	wac := client.Get()

	var code, lang string
	lang = "auto"

	// Check for reply
	quoted := getQuotedText(v)
	if quoted != "" {
		code = quoted
		if len(args) > 0 {
			lang = args[0]
		}
	} else {
		if len(args) == 0 {
			return ReplyErr(v, "Usage: .carbon [lang] <code>\nOr reply to a message with .carbon [lang]")
		}
		// first arg could be a language
		knownLangs := map[string]bool{
			"go": true, "python": true, "js": true, "javascript": true,
			"ts": true, "typescript": true, "rust": true, "c": true,
			"cpp": true, "java": true, "kotlin": true, "swift": true,
			"php": true, "ruby": true, "sh": true, "bash": true,
			"html": true, "css": true, "sql": true, "yaml": true,
			"json": true, "auto": true,
		}
		if len(args) >= 2 && knownLangs[strings.ToLower(args[0])] {
			lang = strings.ToLower(args[0])
			code = strings.Join(args[1:], " ")
		} else {
			code = strings.Join(args, " ")
		}
	}

	if strings.TrimSpace(code) == "" {
		return ReplyErr(v, "❌ No code provided.")
	}

	SendText(v, "🖼️ Generating carbon image...")

	imgBytes, err := fetchCarbonImage(code, lang)
	if err != nil {
		return ReplyErr(v, "❌ Failed to generate carbon: "+err.Error())
	}

	// Save to temp file
	tmp, err := os.CreateTemp("", "carbon-*.png")
	if err != nil {
		return ReplyErr(v, "❌ Temp file error")
	}
	defer os.Remove(tmp.Name())
	tmp.Write(imgBytes)
	tmp.Close()

	// Upload and send as image
	uploaded, err := wac.Upload(context.Background(), imgBytes, whatsmeow.MediaImage)
	if err != nil {
		return ReplyErr(v, "❌ Upload failed: "+err.Error())
	}

	imgMsg := &waE2E.ImageMessage{
		URL:           &uploaded.URL,
		DirectPath:    &uploaded.DirectPath,
		MediaKey:      uploaded.MediaKey,
		FileEncSHA256: uploaded.FileEncSHA256,
		FileSHA256:    uploaded.FileSHA256,
		FileLength:    &uploaded.FileLength,
		Mimetype:      strPtr("image/png"),
		Caption:       strPtr("🖥️ Code generated by PBX Elite"),
	}

	_, err = wac.SendMessage(context.Background(), v.Info.Chat, &waE2E.Message{
		ImageMessage: imgMsg,
	})
	return err
}

// getQuotedText extracts text from a quoted/replied-to message
func getQuotedText(v *events.Message) string {
	if ext := v.Message.GetExtendedTextMessage(); ext != nil {
		if ctx := ext.GetContextInfo(); ctx != nil {
			if qm := ctx.GetQuotedMessage(); qm != nil {
				if qm.GetConversation() != "" {
					return qm.GetConversation()
				}
				if ext2 := qm.GetExtendedTextMessage(); ext2 != nil {
					return ext2.GetText()
				}
			}
		}
	}
	return ""
}

// fallback: carbon via screenshot service
func carbonFallback(code string) ([]byte, error) {
	var b bytes.Buffer
	w := multipart.NewWriter(&b)
	_ = w.WriteField("code", code)
	w.Close()

	resp, err := http.Post(
		"https://carbonara.solopov.dev/api/cook",
		w.FormDataContentType(),
		&b,
	)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	return io.ReadAll(resp.Body)
}

var _ = carbonFallback // suppress unused warning

func init() {
	Register(ModuleInfo{
		Name:        "Carbon",
		Description: "Generate code screenshot (carbon.now.sh style)",
		Commands: []CommandInfo{
			{Pattern: "carbon", Handler: carbonHandler, Sudo: true},
		},
	})
}
